const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    const savedLanguage = window.localStorage.getItem('ruralsaathi.language');
    const initialLanguage = savedLanguage === 'hi' || savedLanguage === 'mr' ? savedLanguage : 'en';
    document.documentElement.lang = initialLanguage;
    return initialLanguage;
  });

  useEffect(() => {
    document.documentElement.lang = language;
    window.localStorage.setItem('ruralsaathi.language', language);
  }, [language]);

  const value = useMemo(() => ({
    language,
    setLanguage: (nextLanguage) => {
      document.documentElement.lang = nextLanguage;
      window.localStorage.setItem('ruralsaathi.language', nextLanguage);
      setLanguage(nextLanguage);
    },
    t: (text, values = {}) => {
      const translated = translations[language]?.[text] ?? text;
      return translated.replace(/\{(\w+)\}/g, (_, key) => values[key] ?? `{${key}}`);
    },
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useTranslation() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useTranslation must be used within LanguageProvider');
  return context;
}
